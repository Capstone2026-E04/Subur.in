-- recommendation_logs.id: UUID -> integer autoincrement.
-- Baris lama dinomori ulang berurutan menurut created_at.
--
-- JALANKAN MANUAL di Supabase SQL Editor SEBELUM deploy backend versi baru.
-- Tidak ada FK lain yang mereferensikan recommendation_logs.id.
BEGIN;

LOCK TABLE recommendation_logs IN ACCESS EXCLUSIVE MODE;

ALTER TABLE recommendation_logs DROP CONSTRAINT recommendation_logs_pkey;
ALTER TABLE recommendation_logs RENAME COLUMN id TO old_id;
ALTER TABLE recommendation_logs ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY;

UPDATE recommendation_logs t SET id = n.rn
FROM (SELECT old_id, row_number() OVER (ORDER BY created_at, old_id) AS rn FROM recommendation_logs) n
WHERE t.old_id = n.old_id;

SELECT setval(pg_get_serial_sequence('recommendation_logs', 'id'),
              COALESCE((SELECT max(id) FROM recommendation_logs), 1),
              (SELECT count(*) > 0 FROM recommendation_logs));

ALTER TABLE recommendation_logs ADD PRIMARY KEY (id);
ALTER TABLE recommendation_logs DROP COLUMN old_id;

COMMIT;
